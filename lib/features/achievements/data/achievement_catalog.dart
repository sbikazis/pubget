    for (final item in definitions) {
      if (item.id == id) return item;
    }
    return null;
  }

  static List<AchievementItem> lockedItems() {
    return definitions
        .map((definition) => AchievementItem(definition: definition, unlocked: false))
        .toList(growable: false);
  }
